/**
 * Convert a skill identifier to PascalCase. Splits on:
 *   - non-alphanumeric runs (e.g. `-`, `_`, ` `, `.`)
 *   - case boundaries (lowercase → uppercase)
 *
 * Examples:
 *   `askDocs`     → `AskDocs`
 *   `ask-docs`    → `AskDocs`
 *   `ask_docs`    → `AskDocs`
 *   `render-chart`→ `RenderChart`
 *   `foo-bar`     → `FooBar`
 *   `fooBar`      → `FooBar`   (collides with `foo-bar`)
 */
export function pascalCase(id: string): string {
  // Insert separator before uppercase letters preceded by lowercase / digit.
  const expanded = id.replace(/([a-z0-9])([A-Z])/g, '$1 $2');
  const words = expanded.split(/[^a-zA-Z0-9]+/).filter((w) => w.length > 0);
  return words
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join('');
}

/** Check whether a string is a valid JS identifier (no quoting required). */
function isValidJsIdentifier(s: string): boolean {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(s);
}

/** Type-guard: is `v` a plain object (record)? */
function isPlainObject(v: unknown): v is Record<string, unknown> {
  return typeof v === 'object' && v !== null && !Array.isArray(v);
}
